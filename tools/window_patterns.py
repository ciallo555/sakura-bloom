def carved_slats(wood, frame, box):
    """Extrude the drawing one pixel deep. Join identical spans in adjacent rows."""
    mask = Image.new("1", (16, 16))
    pen = ImageDraw.Draw(mask)
    for path in WINDOWS[wood][2]:
        pen.line(path, fill=1)

    rows = {}
    for y in range(1, 15):
        for solid, columns in groupby(range(1, 15), lambda x: mask.getpixel((x, y))):
            if solid:
                xs = list(columns)
                rows.setdefault((xs[0], xs[-1] + 1), []).append(y)

    parts = []
    for (left, right), ys in rows.items():
        for _, run in groupby(enumerate(ys), lambda entry: entry[1] - entry[0]):
            heights = [y for _, y in run]
            top, bottom = heights[0], heights[-1] + 1
            part = box((left, 16-bottom, 7.5), (right, 16-top, 8.5), frame)
            # Skip ends buried in the frame or completely covered by an adjoining strip.
            for side, covered in (
                ("west", left == 1 or all(mask.getpixel((left-1, y)) for y in heights)),
                ("east", right == 15 or all(mask.getpixel((right, y)) for y in heights)),
                ("up", top == 1 or all(mask.getpixel((x, top-1)) for x in range(left, right))),
                ("down", bottom == 15 or all(mask.getpixel((x, bottom)) for x in range(left, right))),
            ):
                if covered:
                    del part["faces"][side]
            parts.append(part)
    return parts
